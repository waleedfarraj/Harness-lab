import { Fragment } from "react";
import { Card } from "./primitives";

/** Nemotron's output uses `**bold**` for emphasis; render just that, nothing heavier than this. */
function renderInlineBold(text: string) {
  const parts = text.split(/(\*\*[^*]+\*\*)/g);
  return parts.map((part, i) => {
    const match = /^\*\*([^*]+)\*\*$/.exec(part);
    return match ? <strong key={i} className="font-semibold text-zinc-900 dark:text-zinc-50">{match[1]}</strong> : <Fragment key={i}>{part}</Fragment>;
  });
}

export function MechanismExplanation({ explanation, fixedMechanisms }: { explanation: string | null; fixedMechanisms: string[] }) {
  return (
    <Card className="border-violet-200 bg-violet-50/40 p-6 sm:p-8 dark:border-violet-900/50 dark:bg-violet-500/5">
      <div className="flex items-center justify-between gap-3">
        <p className="text-xs font-semibold uppercase tracking-widest text-violet-700 dark:text-violet-300">What happened?</p>
        <span className="inline-flex items-center gap-1.5 rounded-full bg-violet-100 px-2.5 py-0.5 text-xs font-medium text-violet-700 dark:bg-violet-500/15 dark:text-violet-300">
          Generated by Nemotron from recorded trajectories
        </span>
      </div>

      {explanation ? (
        <p className="mt-3 text-sm leading-relaxed text-zinc-800 dark:text-zinc-200">{renderInlineBold(explanation)}</p>
      ) : (
        <p className="mt-3 text-sm text-zinc-500 dark:text-zinc-500">No mechanism explanation was requested for this diagnosis run.</p>
      )}

      {fixedMechanisms.length > 0 && (
        <div className="mt-5 border-t border-violet-200/70 pt-4 dark:border-violet-900/40">
          <p className="text-xs font-medium uppercase tracking-wide text-zinc-500 dark:text-zinc-500">
            Fixed mechanisms observed <span className="font-normal normal-case">(unchanged between baseline and candidate, but part of how the failure manifested)</span>
          </p>
          <ul className="mt-2 space-y-1 text-sm text-zinc-700 dark:text-zinc-300">
            {fixedMechanisms.map((m) => (
              <li key={m} className="flex gap-2">
                <span className="mt-1.5 h-1 w-1 shrink-0 rounded-full bg-zinc-400 dark:bg-zinc-600" />
                {m}
              </li>
            ))}
          </ul>
        </div>
      )}
    </Card>
  );
}
